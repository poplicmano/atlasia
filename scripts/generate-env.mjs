import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

const target = ".env.local";
if (existsSync(target)) {
  console.log(`${target} already exists; leaving it unchanged. Run "npm run env:check" to verify it.`);
  process.exit(0);
}

const secret = randomBytes(32).toString("base64url");
const password = `Atlasia-${randomBytes(12).toString("base64url")}`;
const content = `# Generated by npm run setup:env. Keep this file private.
APP_SECRET=${secret}
ADMIN_USERNAME=admin
ADMIN_PASSWORD=${password}
ADMIN_DISPLAY_NAME=ATLASIA Administrator
APP_URL=http://localhost:3000
SESSION_TTL_HOURS=12
SESSION_IDLE_HOURS=2
DATABASE_PATH=./data/atlasia.db
`;

const credentials = `ATLASIA local administrator
Username: admin
Password: ${password}

This file was generated for local setup. Copy the credentials, then delete this file.
Do not commit or share it.
`;

writeFileSync(target, content, { mode: 0o600 });
writeFileSync("LOCAL_CREDENTIALS.txt", credentials, { mode: 0o600 });
console.log(`Created ${target} with a random APP_SECRET and administrator password.`);
console.log(`Administrator: admin / ${password}`);
console.log("Credentials were also saved to LOCAL_CREDENTIALS.txt. Delete that file after copying them.");
